import { getMarkdownTemplate } from './report-templates.js';

describe('getMarkdownTemplate — подпись рыночной стоимости', () => {
  const md = getMarkdownTemplate(
    '18.11.2026',
    '612 064,08',
    '458,34',
    60,
    40,
    '• SBER — держать',
  );

  it('уточняет, что рыночная стоимость — без свободных средств', () => {
    expect(md).toContain(
      '**Рыночная стоимость ценных бумаг (без свободных средств):** 612 064,08 руб.',
    );
  });

  it('показывает свободные средства отдельной строкой', () => {
    expect(md).toContain('**Свободные средства:** 458,34 руб.');
  });

  it('объясняет состав C9: бумаги + свободные средства', () => {
    expect(md).toContain(
      '**Текущие активы (C9) = ценные бумаги + свободные средства.**',
    );
  });
});
