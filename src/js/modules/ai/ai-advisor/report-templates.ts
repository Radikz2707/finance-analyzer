/**
 * Собрать markdown-шаблон отчёта о ребалансировке портфеля.
 *
 * Формирует итоговый текст отчёта: дата анализа, рыночная стоимость
 * ценных бумаг, свободные средства, текущий сплит по классам активов
 * и перечень защитных лимитов/дефицитов по инструментам.
 *
 * @param date       Дата анализа (строка, уже отформатированная).
 * @param totalVal   Рыночная стоимость ценных бумаг, руб. (строка).
 * @param freeCash   Свободные средства, руб. (строка).
 * @param stocks     Доля акций в сплите, %.
 * @param bonds      Доля облигаций в сплите, %.
 * @param assetsList Markdown-список анализа лимитов/дефицитов по инструментам.
 * @returns Полный markdown-текст отчёта.
 */
export function getMarkdownTemplate(
  date: string,
  totalVal: string,
  freeCash: string,
  stocks: number,
  bonds: number,
  assetsList: string,
): string {
  return (
    '# 📊 ОТЧЕТ ПО РЕБАЛАНСИРОВКЕ ПОРТФЕЛЯ\n\n' +
    '**Дата анализа:** ' +
    date +
    '\n' +
    '**Рыночная стоимость ценных бумаг:** ' +
    totalVal +
    ' руб.\n' +
    '**Свободные средства:** ' +
    freeCash +
    ' руб.\n\n' +
    '## 📈 Текущий сплит классов активов\n' +
    '* Акции: ' +
    stocks +
    '%\n' +
    '* Облигации: ' +
    bonds +
    '%\n\n' +
    '## 🔍 Анализ защитных лимитов и дефицитов по инструментам:\n' +
    assetsList
  );
}
