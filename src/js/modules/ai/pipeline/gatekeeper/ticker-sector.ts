/**
 * Получить сектор по тикеру.
 * @param ticker - тикер актива
 * @returns сектор или 'Прочее' если не найден
 */
export function getTickerSector(ticker: string): Sector {
  const upper = ticker.toUpperCase();
  return TICKER_SECTOR_MAP[upper] ?? 'Прочее';
}

/**
 * Получить все сектора.
 */
export function getAllSectors(): Sector[] {
  return [...new Set(Object.values(TICKER_SECTOR_MAP))];
}

/**
 * Группировка тикеров по секторам.
 */
export function groupTickersBySector(tickers: string[]): Map<Sector, string[]> {
  const result = new Map<Sector, string[]>();

  for (const ticker of tickers) {
    const sector = getTickerSector(ticker);
    if (!result.has(sector)) {
      result.set(sector, []);
    }
    result.get(sector)!.push(ticker);
  }

  return result;
}
