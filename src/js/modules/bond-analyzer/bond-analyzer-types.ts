/**
 * Bond Analyst — общие типы для анализа облигаций.
 *
 * Этап P0: передача существующих данных QUIK через pipeline.
 * Этап P1: расчёт доходности и процентного риска.
 * Этап P2: кредитный анализ эмитентов.
 * Этап P3: итоговая оценка и интеграция с Director.
 *
 * Ключевые принципы:
 * - Не называть yield YTM до подтверждения семантики QUIK.
 * - Не называть duration модифицированной до подтверждения методики.
 * - Не классифицировать тип купона без достоверных данных.
 * - Разделять рыночные данные (лист «Облигации») и данные позиции (лист QUIK).
 * - Не терять данные при cleanup().
 */

// ──────────────────────────────────────────────
// 1. Типы данных качества
// ──────────────────────────────────────────────

/** Статус доступности данных */
export type DataQualityStatus =
  | 'AVAILABLE'
  | 'PARTIAL'
  | 'MISSING'
  | 'INVALID'
  | 'STALE';

// ──────────────────────────────────────────────
// 2. Тип купона — только после подтверждения
// ──────────────────────────────────────────────

/**
 * Тип купона облигации.
 *
 * НЕ определять FIXED/FLOATER/ZERO_COUPON только по размеру купона,
 * номиналу и рыночной цене. Если нет достоверной информации об условиях
 * выпуска — возвращать UNKNOWN.
 */
export type CouponType = 'FIXED' | 'FLOATER' | 'ZERO_COUPON' | 'UNKNOWN';

// ──────────────────────────────────────────────
// 3. Тип дюрации — только после подтверждения
// ──────────────────────────────────────────────

/**
 * Тип дюрации.
 *
 * НЕ считать поле duration модифицированной дюрацией до подтверждения
 * методики и единиц измерения QUIK.
 */
export type DurationType =
  | 'MACAULAY'
  | 'MODIFIED'
  | 'EFFECTIVE'
  | 'DV01'
  | 'UNKNOWN';

// ──────────────────────────────────────────────
// 4. Рыночные данные облигации (лист «Облигации», A:M)
// ──────────────────────────────────────────────

/**
 * Полные рыночные данные по облигационному выпуску из листа «Облигации».
 *
 * Источник: QUIK → Excel, столбцы A:M.
 * Все числовые показатели сохраняются в исходных единицах измерения.
 *
 * ВАЖНО:
 * - yield — НЕ называть YTM без подтверждения семантики.
 * - duration — НЕ называть модифицированной без подтверждения методики.
 * - couponAmount — не перепутать с couponRub из листа QUIK.
 */
export interface BondMarketData {
  /** A: Инструмент — название выпуска */
  instrumentName: string;
  /** B: ISIN — уникальный идентификатор выпуска */
  isin: string;
  /** C: Листинг — уровень листинга (если есть) */
  listingLevel: string;
  /** D: Цена последняя — рыночная цена (единица: % или RUB) */
  lastPrice: number;
  /**
   * E: Доходность — показатель из QUIK.
   * НЕ называть YTM до подтверждения.
   * Единица измерения: % (уточнить в Excel).
   */
  yield: number;
  /**
   * F: Оборот — объём торгов (единица: RUB, период: уточнить).
   * Использовать для оценки ликвидности.
   */
  turnover: number;
  /** G: Номинал — номинальная стоимость одной облигации (RUB) */
  nominal: number;
  /**
   * H: Размер купона — денежная выплата на одну облигацию.
   * Единица: RUB (уточнить в Excel).
   */
  couponAmount: number;
  /**
   * I: Длительность купона — период между выплатами (дни).
   * Использовать для расчёта частоты выплат.
   */
  couponPeriodDays: number;
  /**
   * J: Дата выплаты купона — ближайшая дата выплаты.
   * Формат: Date (из Excel).
   */
  nextCouponDate: Date | null;
  /**
   * K: НКД — накопленный купонный доход на одну облигацию.
   * Единица: RUB (уточнить в Excel).
   */
  nkd: number;
  /**
   * L: Дата погашения — срок обращения выпуска.
   * Формат: Date (из Excel).
   */
  maturityDate: Date | null;
  /**
   * M: Дюрация — показатель чувствительности к изменению доходности.
   * НЕ называть модифицированной до подтверждения методики.
   * Единица: годы (уточнить в Excel).
   */
  duration: number;
  /** Источник данных */
  source: 'EXCEL_BONDS';
  /**
   * Дата актуальности рыночных данных.
   * Если QUIK не предоставляет дату котировки — использовать дату
   * загрузки книги, но отмечать как STALE.
   */
  asOfDate: Date | null;
}

// ──────────────────────────────────────────────
// 5. Данные позиции (лист QUIK)
// ──────────────────────────────────────────────

/**
 * Данные конкретной позиции облигации в портфеле из листа QUIK.
 *
 * Отличается от BondMarketData: это фактическое состояние позиции,
 * а не рыночный справочник.
 */
export interface BondPositionData {
  /** Тикер / ISIN */
  ticker: string;
  /** Название выпуска */
  name: string;
  /** Количество бумаг */
  quantity: number;
  /** Балансовая цена (рубль) */
  balancePrice: number;
  /** Текущая рыночная цена (рубль) */
  currentPrice: number;
  /** Ликвидационная цена (рубль) */
  liquidationPrice: number;
  /** Доля в портфеле по ликвидационной стоимости (%) */
  liquidationPercent: number;
  /** Балансовая доля (%) */
  balancePercent: number;
  /** Целевая доля (%) */
  targetPercent: number | null;
  /** НКД на позицию (рубль) */
  nkdRub: number;
  /** Купонная ставка (рубль) */
  couponRub: number;
  /** Балансовая стоимость позиции (рубль) */
  balanceValue: number;
  /** Ликвидационная стоимость позиции (рубль) */
  liquidationValue: number;
  /** Динамика позиции (%) */
  dynamicsPercent: number;
  /** Нереализованный P&L (рубль) */
  unrealizedProfitRub: number;
  /** Запрет на продажу */
  holdOnly: boolean;
  /** Исключить из stock pool */
  excludeFromStockPool: boolean;
  /** Идентификатор счёта */
  accountId?: string;
}

// ──────────────────────────────────────────────
// 6. Обогащённые данные позиции (QUIK + рыночные)
// ──────────────────────────────────────────────

/**
 * Обогащённые данные позиции — объединение BondPositionData и BondMarketData.
 *
 * Связывание по ISIN/ticker.
 * Если рыночные данные не найдены — поля из BondMarketData = null.
 */
export interface BondEnrichedData {
  /** Позиция из QUIK */
  position: BondPositionData;
  /** Рыночные данные из листа «Облигации» */
  market: BondMarketData | null;
  /** ISIN для однозначной идентификации выпуска */
  isin: string;
}

// ──────────────────────────────────────────────
// 7. Оценка ликвидности
// ──────────────────────────────────────────────

/** Оценка ликвидности облигации */
export interface LiquidityAssessment {
  /** Статус доступности данных */
  status: DataQualityStatus;
  /** Оборот (из QUIK) */
  turnover: number | null;
  /** Единица измерения оборота (уточнить) */
  turnoverUnit: string | null;
  /** Спред (если есть в источниках) */
  spread: number | null;
  /** Глубина стакана (если есть в источниках) */
  depth: number | null;
  /** Резюме */
  summary: string;
}

// ──────────────────────────────────────────────
// 8. Кредитная оценка
// ──────────────────────────────────────────────

/** Уровень кредитного качества */
export type CreditQuality = 'HIGH' | 'MEDIUM' | 'LOW' | 'INSUFFICIENT_DATA';

/**
 * Кредитная оценка эмитента облигации.
 *
 * НЕ выдавать AI-оценку за официальную кредитную оценку.
 * НЕ рассчитывать количественную вероятность дефолта без модели.
 */
export interface CreditAssessment {
  /** Уровень кредитного качества */
  quality: CreditQuality;
  /** Источник данных */
  source: string;
  /** Дата отчётности */
  asOfDate: string | null;
  /** Финансовые коэффициенты (если есть) */
  financials?: {
    revenue?: number;
    ebitda?: number;
    netProfit?: number;
    netDebt?: number;
    netDebtToEbitda?: number;
    interestCoverage?: number;
    freeCashFlow?: number;
  };
  /** Кредитный рейтинг (если есть) */
  rating?: {
    agency: string;
    rating: string;
    outlook: string;
  };
  /** Резюме */
  summary: string;
}

// ──────────────────────────────────────────────
// 9. Расчёт доходности
// ──────────────────────────────────────────────

/** Проекция купонной выплаты */
export interface CouponProjection {
  /** Дата выплаты */
  date: Date;
  /** Купон на 1 облигацию (RUB) */
  couponPerBond: number;
  /** Купон на позицию (RUB) */
  couponForPosition: number;
  /** Дней до выплаты */
  daysUntil: number;
}

/** Результат расчёта доходности */
export interface YieldAnalysis {
  /** Текущая доходность (Current Yield) */
  currentYield: number | null;
  /**
   * Доходность к погашению.
   * Приоритет: показатель QUIK (столбец E).
   * Самостоятельный расчёт — только при наличии полного графика денежных потоков.
   */
  ytm: number | null;
  /** Эффективная доходность */
  effectiveYield: number | null;
  /** Годовой купонный доход на позицию */
  annualCouponIncome: number | null;
  /** Следующая купонная выплата */
  nextCouponPayment: number | null;
  /** Тип купона */
  couponType: CouponType;
  /** Статус качества данных */
  dataQuality: DataQualityStatus;
}

// ──────────────────────────────────────────────
// 10. Процентный риск
// ──────────────────────────────────────────────

/** Результат анализа процентного риска */
export interface DurationAnalysis {
  /** Значение дюрации (из QUIK, не называть модифицированной без подтверждения) */
  duration: number | null;
  /** Тип дюрации */
  durationType: DurationType;
  /** DV01 — изменение цены при сдвиге доходности на 1 б.п. */
  dv01: number | null;
  /** Сценарии изменения цены */
  scenarios: Array<{
    yieldChangePct: number;
    priceImpactPct: number;
    priceImpactRub: number;
  }>;
  /** Статус качества данных */
  dataQuality: DataQualityStatus;
}

// ──────────────────────────────────────────────
// 11. Итоговая оценка облигации
// ──────────────────────────────────────────────

/** Итоговая рекомендация по облигации */
export type BondRecommendation =
  | 'BUY'
  | 'HOLD'
  | 'REDUCE'
  | 'EXIT'
  | 'WAIT'
  | 'INSUFFICIENT_DATA';

/**
 * Итоговая оценка облигации.
 *
 * Разделять три вопроса:
 * 1. Качество эмитента: способен ли он обслуживать обязательства?
 * 2. Привлекательность выпуска: компенсирует ли доходность принимаемые риски?
 * 3. Портфельная целесообразность: нужно ли увеличивать позицию?
 */
export interface BondFinalAssessment {
  /** Итоговая рекомендация */
  recommendation: BondRecommendation;
  /** Обоснование */
  rationale: string;
  /** Доходность */
  yield: YieldAnalysis;
  /** Процентный риск */
  duration: DurationAnalysis;
  /** Кредитное качество */
  credit: CreditAssessment;
  /** Ликвидность */
  liquidity: LiquidityAssessment;
  /** Недостающие данные */
  missingData: string[];
  /** Согласованность с PortfolioMath */
  mathAgreement: string;
  /** Влияние на структуру портфеля */
  portfolioImpact: string;
}
